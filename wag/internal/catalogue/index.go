package catalogue

import (
	"bytes"
	"fmt"
	"sort"
	"strings"
)

// IndexFile is the catalogue's generated table of contents.
const IndexFile = "index.md"

// progress counts an entry's work items by state.
type progress struct{ items, todo, generated, drafted, verified, disputed int }

func (p *progress) add(status string) {
	p.items++
	st, err := ParseStatus(status)
	if err != nil {
		return
	}
	switch st.State {
	case Todo:
		p.todo++
	case Generated:
		p.generated++
	case "drafted":
		p.drafted++
	case "verified":
		p.verified++
	case "disputed":
		p.disputed++
	}
}

func (p *progress) plus(q progress) {
	p.items += q.items
	p.todo += q.todo
	p.generated += q.generated
	p.drafted += q.drafted
	p.verified += q.verified
	p.disputed += q.disputed
}

// progressOf counts the work items of an entry.
func progressOf(e *Entry) progress {
	var p progress
	for _, x := range e.Book {
		p.add(x.Status)
	}
	for _, x := range e.Families {
		p.add(x.Status)
	}
	for _, x := range e.PremiseMap {
		p.add(x.Status)
	}
	for _, x := range e.CQs {
		p.add(x.Status)
	}
	for _, x := range e.Contrasts {
		p.add(x.Status)
	}
	for _, x := range e.Examples {
		p.add(x.Status)
	}
	for _, x := range e.Discrepancies {
		p.add(x.Status)
	}
	for _, s := range []string{e.Summary.Status, e.Class.Status, e.Specialises.Status, e.DialogueTypes.Status} {
		p.add(s)
	}
	return p
}

// Index renders the catalogue's table of contents: one line per entry,
// tier 1 first, with where its work stands.
func Index(entries []*Entry) []byte {
	es := append([]*Entry(nil), entries...)
	sort.SliceStable(es, func(i, j int) bool {
		if es[i].Tier != es[j].Tier {
			return es[i].Tier < es[j].Tier
		}
		return es[i].ID < es[j].ID
	})
	var b bytes.Buffer
	var total progress
	tiers := map[int]int{}
	for _, e := range es {
		total.plus(progressOf(e))
		tiers[e.Tier]++
	}
	fmt.Fprintf(&b, "# The scheme catalogue: index\n\n")
	fmt.Fprintf(&b, "Generated by `wag-cli --catalogue-gen` from the entries in `schemes/`; do not edit. What the columns mean: [README.md](README.md).\n\n")
	fmt.Fprintf(&b, "**%d entries** (tier 1: %d; tier 2: %d). **%d work items:** %d verified, %d drafted, %d disputed, %d generated (not yet checked by a person), %d to write.\n\n",
		len(es), tiers[1], tiers[2], total.items, total.verified, total.drafted, total.disputed, total.generated, total.todo)
	fmt.Fprintf(&b, "| Scheme | Tier | Book | Family | Game | Questions (book + game) | Verified / items |\n")
	fmt.Fprintf(&b, "|---|---|---|---|---|---|---|\n")
	for _, e := range es {
		var book []string
		for _, r := range e.Book {
			x := r.Entry
			if r.Match != "exact" {
				x += " (" + r.Match + ")"
			}
			book = append(book, x)
		}
		var fams []string
		for _, f := range e.Families {
			fams = append(fams, f.Family)
		}
		game := ""
		if e.Game != nil {
			game = "`" + e.Game.ID + "`"
		}
		nb, ng := 0, 0
		for _, c := range e.CQs {
			if c.Book != nil {
				nb++
			}
			if c.Game != nil && c.Book == nil {
				ng++
			}
		}
		q := fmt.Sprint(nb)
		if ng > 0 {
			q += fmt.Sprintf(" + %d", ng)
		}
		p := progressOf(e)
		fmt.Fprintf(&b, "| [`%s`](schemes/%s.yml) %s | %d | %s | %s | %s | %s | %d / %d |\n",
			e.ID, e.ID, mdEscape(e.Name), e.Tier, strings.Join(book, ", "), strings.Join(fams, ", "), game, q, p.verified, p.items)
	}
	return b.Bytes()
}

func mdEscape(s string) string { return strings.ReplaceAll(s, "|", `\|`) }
