// P1 (docs/e1-evidence.md): the engine's fingerprint computed from the
// vendored sources equals the generated constant; WAG_UPDATE_ENGINE=1
// writes the constant again (after a deliberate change of the engine).
func TestEngineFingerprint(t *testing.T) {
	got, err := EngineSources("../../..")
	if err != nil {
		t.Fatal(err)
	}
	if os.Getenv("WAG_UPDATE_ENGINE") != "" {
		src := fmt.Sprintf("// Code generated by TestEngineFingerprint (WAG_UPDATE_ENGINE=1); DO NOT EDIT.\n\npackage manifest\n\n"+
			"// EngineSHA256 is the engine's fingerprint (EngineSources), generated from the\n// vendored sources.\nconst EngineSHA256 = %q\n", got)
		if err := os.WriteFile("engine_sha256.go", []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	if got != EngineSHA256 {
		t.Fatalf("the engine's sources fingerprint %s, the build says %s: regenerate it (WAG_UPDATE_ENGINE=1 go test -run TestEngineFingerprint ./internal/manifest/) after a deliberate change of the engine", got, EngineSHA256)
	}
}

// P1: one byte changed in an engine source changes the fingerprint; a test
// file does not count, nor a CRLF checkout.
func TestEngineFingerprintFollowsTheSources(t *testing.T) {
	root := t.TempDir()
	write := func(p, s string) {
		full := filepath.Join(root, filepath.FromSlash(p))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(full, []byte(s), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("carneades-4/go.mod", "module x\n")
	write("GoCHR/go.mod", "module y\n")
	write("carneades-4/src/engine/caes/a.go", "package caes\n")
	write("GoCHR/src/engine/CHR/b.go", "package CHR\n")
	base, err := EngineSources(root)
	if err != nil {
		t.Fatal(err)
	}
	write("carneades-4/src/engine/caes/a_test.go", "package caes\n// a test\n")
	write("carneades-4/src/engine/caes/a.go", "package caes\r\n")
	if same, _ := EngineSources(root); same != base {
		t.Fatal("a test file or a CRLF checkout changed the fingerprint")
	}
	write("GoCHR/src/engine/CHR/b.go", "package CHR \n")
	if changed, _ := EngineSources(root); changed == base {
		t.Fatal("a changed source left the fingerprint as it was")
	}
}

// P2's form and P3: each pin is 64 hexadecimal digits; the scheme file's and
// the NASCQ data's follow their bytes, not their line endings.
func TestPinsFollowTheData(t *testing.T) {
	hex64 := regexp.MustCompile(`^[0-9a-f]{64}$`)
	p := Of([]byte("schemes: []\n"), []byte("{}"), []byte("{}"), []byte("{}"))
	for _, v := range []string{p.Engine, p.Catalogue, p.NASCQ} {
		if !hex64.MatchString(v) {
			t.Fatalf("pin %q", v)
		}
	}
	if q := Of([]byte("schemes: []\r\n"), []byte("{}"), []byte("{}"), []byte("{}")); q != p {
		t.Fatal("a CRLF scheme file changed the pins")
	}
	if q := Of([]byte("schemes: [] \n"), []byte("{}"), []byte("{}"), []byte("{}")); q.Catalogue == p.Catalogue || q.NASCQ != p.NASCQ {
		t.Fatal("the scheme file's pin does not follow it alone")
	}
	if q := Of([]byte("schemes: []\n"), []byte("{}"), []byte("{} "), []byte("{}")); q.NASCQ == p.NASCQ || q.Catalogue != p.Catalogue {
		t.Fatal("the NASCQ pin does not follow the questions alone")
	}
	if NASCQ([]byte("a"), []byte("b"), nil) == NASCQ([]byte("ab"), nil, nil) {
		t.Fatal("the NASCQ pin does not separate its files")
	}
}
